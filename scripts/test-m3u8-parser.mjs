#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../js/player.js',import.meta.url),'utf8');
const start=source.indexOf('    function resolveUrl(uri, base) {');
const end=source.indexOf('    function fmtDuration(sec) {',start);
assert.ok(start>=0&&end>start,'production parser anchors must exist');
const sandbox={URL};
vm.runInNewContext(source.slice(start,end)+'\nthis.__parseManifest=parseManifest;',sandbox);
const parse=sandbox.__parseManifest;
assert.equal(typeof parse,'function');
const base='https://cdn.example.test/live/master.m3u8';
const master=parse(['#EXTM3U','#EXT-X-VERSION:7','#EXT-X-STREAM-INF:BANDWIDTH=1280000,RESOLUTION=1280x720','video/720.m3u8'].join('\n'),base);
assert.equal(master.isMaster,true);assert.equal(master.version,'7');assert.equal(master.variants.length,1);
assert.equal(master.variants[0].BANDWIDTH,'1280000');assert.equal(master.variants[0].RESOLUTION,'1280x720');
assert.equal(master.variants[0].uri,'https://cdn.example.test/live/video/720.m3u8');
const vod=parse(['#EXTM3U','#EXT-X-TARGETDURATION:6','#EXT-X-MEDIA-SEQUENCE:42','#EXT-X-PLAYLIST-TYPE:VOD','#EXTINF:6.0,','seg-42.ts','#EXTINF:4.5,','seg-43.ts','#EXT-X-ENDLIST'].join('\n'),base);
assert.equal(vod.targetDuration,6);assert.equal(vod.mediaSequence,42);assert.equal(vod.playlistType,'VOD');assert.equal(vod.endList,true);
assert.equal(vod.segments.length,2);assert.equal(vod.totalDuration,10.5);
const event=parse('#EXTM3U\r\n#EXT-X-TARGETDURATION:8\r\n#EXT-X-MEDIA-SEQUENCE:105\r\n#EXT-X-PLAYLIST-TYPE:EVENT\r\n#EXTINF:8,\r\npart-105.ts\r\n',base);
assert.equal(event.targetDuration,8);assert.equal(event.mediaSequence,105);assert.equal(event.playlistType,'EVENT');assert.equal(event.endList,false);
assert.equal(event.segments[0].uri,'https://cdn.example.test/live/part-105.ts');
const live=parse('#EXTM3U\n#EXT-X-TARGETDURATION:4\n#EXT-X-MEDIA-SEQUENCE:9\n#EXTINF:4,\nseg.ts',base);
assert.equal(live.targetDuration,4);assert.equal(live.mediaSequence,9);assert.equal(live.playlistType,'');assert.equal(live.endList,false);
const empty=parse('#EXTM3U\n#EXT-X-TARGETDURATION:\n#EXT-X-MEDIA-SEQUENCE:\n#EXT-X-PLAYLIST-TYPE:\n',base);
assert.equal(empty.targetDuration,0);assert.equal(empty.mediaSequence,0);assert.equal(empty.playlistType,'');
const invalid=parse('#EXTM3U\n#EXT-X-TARGETDURATION:abc\n#EXT-X-MEDIA-SEQUENCE:abc',base);
assert.equal(invalid.targetDuration,0);assert.equal(invalid.mediaSequence,0);assert.equal(invalid.segments.length,0);
const encrypted=parse('#EXTM3U\n#EXT-X-KEY:METHOD=AES-128,URI="key.bin"\n#EXTINF:2,\nseg.ts',base);
assert.equal(encrypted.encrypted,true);assert.equal(encrypted.keyMethod,'AES-128');
const clear=parse('#EXTM3U\n#EXT-X-KEY:METHOD=NONE\n#EXTINF:2,\nseg.ts',base);
assert.equal(clear.encrypted,false);
console.log('PASS: production M3U8 parser regression (master, VOD, LIVE, EVENT, CRLF, empty/invalid values, URL resolution, encryption markers)');
